/**
 * Снимает координаты активов с присланной карты-схемы (SVG).
 *
 * На схеме каждый актив — кружок с номером, но координат при нём нет, только
 * положение в пикселях. Города на схеме подписаны текстом, и якорь подписи
 * смещён от самой точки, поэтому привязываться к ним нельзя — уедет всё.
 *
 * Поэтому привязка идёт по самим активам: у семи из двенадцати координаты
 * подтверждены в OpenStreetMap, они и задают преобразование «пиксели → градусы».
 * Схема построена в равнопромежуточной сетке, так что хватает аффинного
 * приближения; невязка на опорных точках печатается — по ней видно, можно ли
 * верить снятому.
 *
 * Запуск:  node снять_с_карты.js "путь/к/карте.svg"
 */
const fs = require('fs');

const ФАЙЛ = process.argv[2];
if (!ФАЙЛ){ console.error('нужен путь к SVG'); process.exit(1); }
const svg = fs.readFileSync(ФАЙЛ, 'utf8');

/* Кружки активов: у них есть номер, он же подпись рядом. Берём кружки радиуса 9 —
   легенда внизу нарисована шестёрками и в выборку не идёт. */
const кружки = [...svg.matchAll(/<circle[^>]*\br="9"[^>]*>/g)].map(m => {
  const ч = a => +(m[0].match(new RegExp(a + '="([\\d.-]+)"')) || [])[1];
  return { x: ч('cx'), y: ч('cy') };
});

/* Номер при кружке — отдельный <text> ровно в той же точке */
const номера = [...svg.matchAll(/<text[^>]*x="([\d.]+)"[^>]*y="([\d.]+)"[^>]*>\s*(\d+)\s*<\/text>/g)]
  .map(m => ({ x:+m[1], y:+m[2], н:+m[3] }));

const АКТИВ = {};
for (const к of кружки){
  const б = номера.find(н => Math.hypot(н.x - к.x, н.y - к.y) < 6);
  if (б) АКТИВ[б.н] = к;
}

const ИМЕНА = {
  1:'В. Молдабек', 2:'С. Нуржанова', 3:'Узень', 4:'Карамандыбас',
  5:'Каратобе Южное', 6:'Каламкас', 7:'Жетыбай', 8:'Каражанбас',
  9:'Асар', 10:'Алибекмола', 11:'Кожасай', 12:'Акшабулак Ц',
};

/* Опора: активы, найденные в OSM как настоящие объекты (промысел или посёлок
   при нём). Пять остальных на схеме есть, а в OSM их нет — их и снимаем. */
const ОПОРА = {
  2:[53.270, 45.874], 3:[52.856, 43.338], 6:[51.966, 44.735],
  7:[52.101, 43.588], 8:[51.395, 45.128], 11:[57.114, 48.217], 12:[65.721, 45.953],
};

/* Аффинное приближение методом наименьших квадратов: x = a·д + b·ш + c и то же
   для y. Решаем две системы 3×3 методом Гаусса. */
function приблизить(пары, ось){
  const A = [[0,0,0],[0,0,0],[0,0,0]], B = [0,0,0];
  for (const { д, ш, з } of пары){
    const v = [д, ш, 1];
    for (let i = 0; i < 3; i++){
      for (let j = 0; j < 3; j++) A[i][j] += v[i] * v[j];
      B[i] += v[i] * з;
    }
  }
  for (let i = 0; i < 3; i++){
    let гл = i;
    for (let k = i + 1; k < 3; k++) if (Math.abs(A[k][i]) > Math.abs(A[гл][i])) гл = k;
    [A[i], A[гл]] = [A[гл], A[i]]; [B[i], B[гл]] = [B[гл], B[i]];
    for (let k = i + 1; k < 3; k++){
      const f = A[k][i] / A[i][i];
      for (let j = i; j < 3; j++) A[k][j] -= f * A[i][j];
      B[k] -= f * B[i];
    }
  }
  const р = [0,0,0];
  for (let i = 2; i >= 0; i--){
    let s = B[i];
    for (let j = i + 1; j < 3; j++) s -= A[i][j] * р[j];
    р[i] = s / A[i][i];
  }
  return р;
}

const пары = Object.entries(ОПОРА).map(([н, [д, ш]]) => ({ н:+н, д, ш, к:АКТИВ[н] }));
if (пары.some(п => !п.к)){ console.error('на схеме нет кружка для опорного актива'); process.exit(1); }

const кX = приблизить(пары.map(п => ({ д:п.д, ш:п.ш, з:п.к.x })));
const кY = приблизить(пары.map(п => ({ д:п.д, ш:п.ш, з:п.к.y })));

console.log('невязка на опорных точках (пиксели схемы):');
let макс = 0;
for (const п of пары){
  const x = кX[0]*п.д + кX[1]*п.ш + кX[2], y = кY[0]*п.д + кY[1]*п.ш + кY[2];
  const d = Math.hypot(x - п.к.x, y - п.к.y);
  макс = Math.max(макс, d);
  console.log(`  ${ИМЕНА[п.н].padEnd(16)} ${d.toFixed(1)} px`);
}
/* Масштаб схемы: сколько градусов приходится на пиксель — по нему невязка
   переводится в честную погрешность на местности */
const наПиксель = 1 / Math.hypot(кX[0], кY[0]);
console.log(`масштаб схемы: ${наПиксель.toFixed(3)}° долготы на пиксель`);
console.log(`худшая невязка: ${(макс * наПиксель).toFixed(2)}° ≈ ${(макс * наПиксель * 78).toFixed(0)} км\n`);

// обращение: из пикселей обратно в градусы
const опр = кX[0]*кY[1] - кX[1]*кY[0];
const вГрадусы = (x, y) => {
  const dx = x - кX[2], dy = y - кY[2];
  return [(dx*кY[1] - dy*кX[1]) / опр, (кX[0]*dy - кY[0]*dx) / опр];
};

/* Общее преобразование по всей схеме врёт на градус: рисунок сделан от руки,
   и искажение в разных углах разное. Зато локально схема честна — соседние
   активы стоят друг относительно друга верно. Поэтому неизвестный актив
   ставится не по общей формуле, а от ближайшего подтверждённого соседа:
   берём смещение между ними в пикселях, переводим в градусы и откладываем от
   настоящих координат соседа. */
console.log('снятые координаты:');
for (const н of Object.keys(ИМЕНА).map(Number).sort((a,b)=>a-b)){
  const к = АКТИВ[н];
  if (!к){ console.log(`  ${н}. ${ИМЕНА[н]} — нет на схеме`); continue; }
  const о = ОПОРА[н];
  if (о){
    console.log(`  ${String(н).padStart(2)}. ${ИМЕНА[н].padEnd(16)} [${о[0].toFixed(2)}, ${о[1].toFixed(2)}]  osm`);
    continue;
  }
  let сосед = null, ближе = Infinity;
  for (const п of пары){
    const d = Math.hypot(п.к.x - к.x, п.к.y - к.y);
    if (d < ближе){ ближе = d; сосед = п; }
  }
  const [дс, шс] = вГрадусы(сосед.к.x, сосед.к.y);
  const [дт, шт] = вГрадусы(к.x, к.y);
  const д = ОПОРА[сосед.н][0] + (дт - дс);
  const ш = ОПОРА[сосед.н][1] + (шт - шс);
  console.log(`  ${String(н).padStart(2)}. ${ИМЕНА[н].padEnd(16)} [${д.toFixed(2)}, ${ш.toFixed(2)}]  `
            + `от «${ИМЕНА[сосед.н]}» (${ближе.toFixed(0)} px ≈ ${(ближе*наПиксель*78).toFixed(0)} км)`);
}
