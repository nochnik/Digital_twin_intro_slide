/**
 * Ищет координаты приоритетных активов в OpenStreetMap.
 *
 * Месторождение — не населённый пункт, и в OSM оно есть далеко не всегда.
 * Поэтому на каждый актив идёт несколько запросов: само название, название
 * с «месторождение», казахское написание, посёлок при промысле. Что нашлось —
 * печатается с типом объекта, чтобы было видно, чему верить.
 *
 * Запуск:  node найти_активы.js
 */
const https = require('https');

const качать = url => new Promise((ок, нет) => {
  https.get(url, { headers: { 'User-Agent': 'kmg-digital-twin-slide/1.0 (asset geocode)' } }, r => {
    if (r.statusCode !== 200) return нет(new Error(r.statusCode));
    let d = ''; r.on('data', c => d += c); r.on('end', () => ок(JSON.parse(d)));
  }).on('error', нет);
});
const пауза = мс => new Promise(р => setTimeout(р, мс));

const АКТИВЫ = [
  ['В. Молдабек',      ['Восточный Молдабек', 'Молдабек', 'Шығыс Молдабек', 'Кызылкога']],
  ['С. Нуржанов',      ['месторождение Нуржанова', 'Нуржанов', 'Прорва Атырауская']],
  ['Узень',            ['Узень месторождение', 'Өзен кен орны', 'Жанаозен']],
  ['Карамандыбас',     ['Карамандыбас', 'Қарамандыбас']],
  ['Каратобе Южное',   ['Южный Каратобе', 'Каратобе Мангистау', 'Оңтүстік Қаратөбе']],
  ['Каламкас',         ['Каламкас', 'Қаламқас']],
  ['Жетыбай',          ['Жетыбай', 'Жетібай']],
  ['Каражанбас',       ['Каражанбас', 'Қаражанбас']],
  ['Асар',             ['Асар Мангистау', 'Асар кен орны']],
  ['Алибекмола',       ['Алибекмола', 'Әлібекмола']],
  ['Кожасай',          ['Кожасай', 'Қожасай']],
  ['Акшабулак Ц',      ['Акшабулак', 'Ақшабұлақ']],
];

(async () => {
  for (const [имя, запросы] of АКТИВЫ){
    const найдено = [];
    for (const з of запросы){
      const url = 'https://nominatim.openstreetmap.org/search?q=' + encodeURIComponent(з)
                + '&countrycodes=kz&format=jsonv2&limit=3';
      try {
        for (const о of await качать(url))
          найдено.push(`${(+о.lon).toFixed(3)},${(+о.lat).toFixed(3)} ${о.type}/${о.category} «${о.name || о.display_name.split(',')[0]}»`);
      } catch(e){ найдено.push('ошибка ' + e.message); }
      await пауза(1100);
    }
    console.log(`\n${имя}`);
    if (!найдено.length) console.log('  — ничего');
    for (const с of [...new Set(найдено)]) console.log('  ' + с);
  }
})();
