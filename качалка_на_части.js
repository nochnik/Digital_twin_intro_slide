/**
 * Режет Качалка.glb на подвижные части и облегчает её.
 *
 *   node качалка_на_части.js
 *   Качалка.glb (60,9 МБ, 1,6 млн треугольников) → качалка_части.glb (~1,5 МБ)
 *
 * Зачем. Модель приходит одним сплошным мешем без анимаций: ни коромысла, ни
 * кривошипа отдельными узлами в ней нет, качать нечего. Части приходится
 * выделять по координатам — благо у отдельно стоящей качалки анатомия читается
 * однозначно, в отличие от слипшегося промысла в слое наземки.
 *
 * Границы и оси сняты с самой модели: силуэт отрисовывался покадрово с
 * координатной сеткой, а шатун и противовесы нашлись раскраской по ширине —
 * они вынесены наружу, |z| > 0,15, тогда как коромысло идёт по центру.
 *
 * Облегчение — кластеризация по сетке: вершины в одной ячейке сливаются в одну.
 * Для объекта в 60 пикселей на экране этого достаточно, а вес падает в сорок
 * раз. Развёртка и нормали не сохраняются: фотофактура на таком размере не
 * читается, а нормали three.js пересчитает сам.
 */
const fs = require('fs');
const path = require('path');

const ВХОД  = path.join(__dirname, 'Качалка.glb');
const ВЫХОД = path.join(__dirname, 'качалка_части.glb');
const ШАГ   = 0.0075;          // сторона ячейки слияния, в единицах модели

/* Второй набор — под оцифровку. На полной сетке wireframe сливается в белое
   пятно: у станка триангуляция в тысячу раз плотнее, чем у плит слоёв. Каркас
   строится по огрублённой копии, и ячейка выбрана так, чтобы треугольники на
   экране получались того же размера, что у остальных слоёв: 0,09 модели при
   масштабе 31,5 — это около 2,8 единицы сцены, шаг сетки плиты.

   Чертёж по рёбрам тут пробовался и отброшен: линия в пиксель читается как
   тонкая паутина и выпадает из общей манеры показа.

   Каркас раздувается по нормалям наружу: огрублённая копия местами уходит
   внутрь детального корпуса на величину до полушага ячейки, и при включённой
   проверке глубины эти куски срезались бы — линии пропадали дырами. После
   раздувания каркас сидит поверх железа, как чехол.

   Плотность — промежуточная. Полная сетка (308 тыс. треугольников на станок)
   в аддитивном смешении выгорает в белый при любом цвете; грубая (0,09) была
   отвергнута как «клетчатая». Шаг 0,05 даёт ~9 тыс. на станок — потолок
   «до 10 тысяч» задан заказчиком 16.08.2026, цвет каркаса читается. */
const ШАГ_КАРКАС = 0.05;
const РАЗДУТЬ = 0.025;
/* Слияние по ячейкам оставляет сетку «мятой»: вершина встаёт в среднее своей
   ячейки, и на решётчатой стойке треугольники торчат кто куда. Сглаживание
   Таубина (пара λ/μ, без усадки) раскладывает их по поверхности ровно — как
   у запечённых объектов слоя. */
const СГЛАДИТЬ = 2;            // итераций; при мелкой ячейке хватает лёгкого прохода

/* ── оси механизма (единицы модели) ───────────────────────────────────
   ОСЬ      — опора коромысла на стойке;
   ВАЛ      — вал кривошипа;
   ПАЛЕЦ    — палец кривошипа, к нему крепится низ шатуна;
   ВЕРХШ    — палец на коромысле, к нему крепится верх шатуна.
   Из них считается вся кинематика: радиус кривошипа 0,269, длина шатуна
   0,778, задняя половина коромысла 0,542. */
const ОСЬ    = [-0.280,  0.560];
const ВАЛ    = [ 0.326, -0.287];
const ПАЛЕЦ  = [ 0.484, -0.069];
const ВЕРХШ  = [ 0.250,  0.673];

const наОтрезке = (x, y, a, b, полуш) => {
  const dx = b[0]-a[0], dy = b[1]-a[1], L2 = dx*dx + dy*dy;
  const t = ((x-a[0])*dx + (y-a[1])*dy) / L2;
  if (t < -0.06 || t > 1.06) return false;
  return (x - (a[0]+dx*t))**2 + (y - (a[1]+dy*t))**2 < полуш*полуш;
};

/* Порядок проверок важен: шатун лежит поверх кривошипа и должен отделиться
   первым, иначе уедет вместе с ним. */
const ЧАСТИ = ['рама', 'коромысло', 'кривошип', 'шатун'];
function чья(x, y, z){
  if (Math.abs(z) > 0.15 && наОтрезке(x, y, ВЕРХШ, ПАЛЕЦ, 0.075)) return 3;
  // коромысло: всё выше седла плюс головка, которая свешивается низко
  if (y > 0.59 || (x < -0.58 && y > 0.12)) return 1;
  // кривошип: круг вокруг вала, не залезая в редуктор под ним и в стойку слева
  if (Math.hypot(x-ВАЛ[0], y-ВАЛ[1]) < 0.65 && y > -0.45 && x > 0.15) return 2;
  return 0;
}

// ── разбор входного файла ──────────────────────────────────────────────
const buf = fs.readFileSync(ВХОД);
if (buf.readUInt32LE(0) !== 0x46546C67) throw new Error('не glb: ' + ВХОД);
let off = 12, g = null, bin = null;
while (off < buf.length){
  const len = buf.readUInt32LE(off), тип = buf.readUInt32LE(off + 4);
  const тело = buf.subarray(off + 8, off + 8 + len);
  if (тип === 0x4E4F534A) g = JSON.parse(тело.toString('utf8'));
  if (тип === 0x004E4942) bin = тело;
  off += 8 + len + ((4 - (len % 4)) % 4);
}
function акс(i){
  const a = g.accessors[i], bv = g.bufferViews[a.bufferView];
  const н = (bv.byteOffset||0) + (a.byteOffset||0);
  const [T, р] = {5121:[Uint8Array,1],5123:[Uint16Array,2],5125:[Uint32Array,4],5126:[Float32Array,4]}[a.componentType];
  const шт = {SCALAR:1,VEC2:2,VEC3:3,VEC4:4}[a.type];
  return new T(bin.buffer.slice(bin.byteOffset+н, bin.byteOffset+н + a.count*шт*р));
}
const прим = g.meshes[0].primitives[0];
const P = акс(прим.attributes.POSITION);
const I = акс(прим.indices);
console.log(`вход: ${(buf.length/1048576).toFixed(1)} МБ, ${I.length/3} треугольников`);

// ── раскладка треугольников по частям ──────────────────────────────────
const треуг = ЧАСТИ.map(() => []);
for (let t = 0; t < I.length; t += 3){
  const a = I[t], b = I[t+1], c = I[t+2];
  const cx = (P[a*3]   + P[b*3]   + P[c*3])   / 3;
  const cy = (P[a*3+1] + P[b*3+1] + P[c*3+1]) / 3;
  const cz = (P[a*3+2] + P[b*3+2] + P[c*3+2]) / 3;
  треуг[чья(cx, cy, cz)].push(a, b, c);
}

/* ── слияние вершин по сетке ───────────────────────────────────────────
   Вершины одной ячейки заменяются их средним. Треугольник, у которого две
   вершины попали в одну ячейку, вырождается в отрезок и выбрасывается. */
function облегчить(индексы, шаг = ШАГ){
  const ячейка = new Map(), суммы = [];
  const карта = new Map();
  for (const v of индексы){
    if (карта.has(v)) continue;
    const x = P[v*3], y = P[v*3+1], z = P[v*3+2];
    const k = Math.floor(x/шаг) + ',' + Math.floor(y/шаг) + ',' + Math.floor(z/шаг);
    let n = ячейка.get(k);
    if (n === undefined){ n = суммы.length; ячейка.set(k, n); суммы.push([0,0,0,0]); }
    const s = суммы[n]; s[0]+=x; s[1]+=y; s[2]+=z; s[3]++;
    карта.set(v, n);
  }
  const поз = new Float32Array(суммы.length*3);
  суммы.forEach((s, i) => { поз[i*3]=s[0]/s[3]; поз[i*3+1]=s[1]/s[3]; поз[i*3+2]=s[2]/s[3]; });
  const инд = [];
  for (let t = 0; t < индексы.length; t += 3){
    const a = карта.get(индексы[t]), b = карта.get(индексы[t+1]), c = карта.get(индексы[t+2]);
    if (a === b || b === c || a === c) continue;
    инд.push(a, b, c);
  }
  return { поз, инд };
}

/* Рёбра детали: оставляем те, где грани сходятся под углом больше порога, и
   все одиночные (край поверхности). Ровные участки отбрасываются — на них
   ребра нет, есть только триангуляция. */
function рёбра(поз, инд){
  const кос = Math.cos(УГОЛ_РЕБРА * Math.PI / 180);
  const норм = (a, b, c) => {
    const ax=поз[b*3]-поз[a*3], ay=поз[b*3+1]-поз[a*3+1], az=поз[b*3+2]-поз[a*3+2];
    const bx=поз[c*3]-поз[a*3], by=поз[c*3+1]-поз[a*3+1], bz=поз[c*3+2]-поз[a*3+2];
    const x=ay*bz-az*by, y=az*bx-ax*bz, z=ax*by-ay*bx;
    const д=Math.hypot(x,y,z) || 1;
    return [x/д, y/д, z/д];
  };
  const карта = new Map();
  for (let t = 0; t < инд.length; t += 3){
    const a=инд[t], b=инд[t+1], c=инд[t+2];
    const н = норм(a, b, c);
    for (const [i, j] of [[a,b],[b,c],[c,a]]){
      const k = i < j ? i*1e7 + j : j*1e7 + i;
      const е = карта.get(k);
      if (!е) карта.set(k, { i, j, н, в:null });
      else if (!е.в) е.в = н;
    }
  }
  const линии = [];
  for (const е of карта.values()){
    if (!е.в || е.н[0]*е.в[0] + е.н[1]*е.в[1] + е.н[2]*е.в[2] < кос) линии.push(е.i, е.j);
  }
  return линии;
}

// ── сборка нового glb ──────────────────────────────────────────────────
const куски = [];          // байты
let смещение = 0;
const виды = [], аксессоры = [], сетки = [], узлы = [];

function положить(данные){
  const б = Buffer.from(данные.buffer, данные.byteOffset, данные.byteLength);
  const выравн = (4 - (смещение % 4)) % 4;
  if (выравн){ куски.push(Buffer.alloc(выравн)); смещение += выравн; }
  куски.push(б);
  const вид = { buffer:0, byteOffset:смещение, byteLength:б.length };
  смещение += б.length;
  виды.push(вид);
  return виды.length - 1;
}

/* Сглаживание Таубина: шаг к среднему соседей (λ), затем шаг обратно (μ) —
   мятость уходит, а объём не усыхает, как у чистого Лапласа. */
function сгладить(поз, инд, итераций){
  const n = поз.length/3;
  const соседи = Array.from({length:n}, () => new Set());
  for (let t = 0; t < инд.length; t += 3){
    const [a,b,c] = [инд[t], инд[t+1], инд[t+2]];
    соседи[a].add(b).add(c); соседи[b].add(a).add(c); соседи[c].add(a).add(b);
  }
  const нов = new Float32Array(поз.length);
  const шаг = k => {
    for (let v = 0; v < n; v++){
      if (!соседи[v].size){ нов[v*3]=поз[v*3]; нов[v*3+1]=поз[v*3+1]; нов[v*3+2]=поз[v*3+2]; continue; }
      let x=0,y=0,z=0;
      for (const s of соседи[v]){ x+=поз[s*3]; y+=поз[s*3+1]; z+=поз[s*3+2]; }
      const m = соседи[v].size;
      нов[v*3]   = поз[v*3]   + k*(x/m - поз[v*3]);
      нов[v*3+1] = поз[v*3+1] + k*(y/m - поз[v*3+1]);
      нов[v*3+2] = поз[v*3+2] + k*(z/m - поз[v*3+2]);
    }
    поз.set(нов);
  };
  for (let i = 0; i < итераций; i++){ шаг(0.5); шаг(-0.53); }
}

/* Сдвиг всех вершин наружу по усреднённым нормалям граней. */
function раздуть(поз, инд, δ){
  const н = new Float32Array(поз.length);
  for (let t = 0; t < инд.length; t += 3){
    const [a, b, c] = [инд[t], инд[t+1], инд[t+2]];
    const ax=поз[b*3]-поз[a*3], ay=поз[b*3+1]-поз[a*3+1], az=поз[b*3+2]-поз[a*3+2];
    const bx=поз[c*3]-поз[a*3], by=поз[c*3+1]-поз[a*3+1], bz=поз[c*3+2]-поз[a*3+2];
    const x=ay*bz-az*by, y=az*bx-ax*bz, z=ax*by-ay*bx;
    for (const v of [a, b, c]){ н[v*3]+=x; н[v*3+1]+=y; н[v*3+2]+=z; }
  }
  for (let v = 0; v < поз.length/3; v++){
    const д = Math.hypot(н[v*3], н[v*3+1], н[v*3+2]);
    if (д < 1e-12) continue;
    поз[v*3]   += н[v*3]/д*δ;
    поз[v*3+1] += н[v*3+1]/д*δ;
    поз[v*3+2] += н[v*3+2]/д*δ;
  }
}

function добавить(имя, индексы, шаг, режим){
  const { поз, инд } = облегчить(индексы, шаг);
  if (режим === 2){ сгладить(поз, инд, СГЛАДИТЬ); раздуть(поз, инд, РАЗДУТЬ); }
  const инд32 = new Uint32Array(режим === 1 ? рёбра(поз, инд) : инд);
  let mn = [1e9,1e9,1e9], mx = [-1e9,-1e9,-1e9];
  for (let v = 0; v < поз.length; v += 3) for (let k = 0; k < 3; k++){
    if (поз[v+k] < mn[k]) mn[k] = поз[v+k];
    if (поз[v+k] > mx[k]) mx[k] = поз[v+k];
  }
  const вПоз = положить(поз), вИнд = положить(инд32);
  виды[вПоз].target = 34962; виды[вИнд].target = 34963;
  аксессоры.push({ bufferView:вПоз, componentType:5126, count:поз.length/3, type:'VEC3', min:mn, max:mx });
  аксессоры.push({ bufferView:вИнд, componentType:5125, count:инд32.length, type:'SCALAR' });
  const прим = { attributes:{ POSITION:аксессоры.length-2 }, indices:аксессоры.length-1 };
  if (режим === 1) прим.mode = 1;                    // LINES — грузится как LineSegments
  сетки.push({ name:имя, primitives:[прим] });
  узлы.push({ name:имя, mesh:сетки.length-1 });
  return режим === 1 ? инд32.length/2 : инд32.length/3;
}

ЧАСТИ.forEach((имя, i) => {
  const т  = добавить(имя, треуг[i], ШАГ);
  const тк = добавить(имя + '_каркас', треуг[i], ШАГ_КАРКАС, 2);
  console.log(`  ${имя}: ${треуг[i].length/3} → ${т} треугольников (каркас ${тк})`);
});

const БИН = Buffer.concat(куски);
const json = { asset:{ version:'2.0', generator:'качалка_на_части.js' },
  scene:0, scenes:[{ nodes: узлы.map((_, i) => i) }],
  nodes:узлы, meshes:сетки, accessors:аксессоры, bufferViews:виды,
  buffers:[{ byteLength:БИН.length }] };

const jsonБуф = Buffer.from(JSON.stringify(json), 'utf8');
const jsonПад = Buffer.concat([jsonБуф, Buffer.alloc((4 - (jsonБуф.length % 4)) % 4, 0x20)]);
const бинПад  = Buffer.concat([БИН, Buffer.alloc((4 - (БИН.length % 4)) % 4)]);
const глава = Buffer.alloc(12);
глава.writeUInt32LE(0x46546C67, 0); глава.writeUInt32LE(2, 4);
глава.writeUInt32LE(12 + 8 + jsonПад.length + 8 + бинПад.length, 8);
const кусок = (тип, тело) => {
  const ш = Buffer.alloc(8); ш.writeUInt32LE(тело.length, 0); ш.writeUInt32LE(тип, 4);
  return Buffer.concat([ш, тело]);
};
fs.writeFileSync(ВЫХОД, Buffer.concat([глава,
  кусок(0x4E4F534A, jsonПад), кусок(0x004E4942, бинПад)]));

console.log(`выход: ${(fs.statSync(ВЫХОД).size/1048576).toFixed(2)} МБ → ${path.basename(ВЫХОД)}`);
